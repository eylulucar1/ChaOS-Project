static inline uint8_t GetFontRow(char c, uint8_t row) {
    if (c < 32 || c > 126 || row >= 16) {
        return 0;
    }
    uint8_t index = (uint8_t)(c - 32);
    uint8_t r = row >> 1;
    if (r < 4) {
        return (uint8_t)((SystemFontTable[index].topRows >> ((3 - r) * 8)) & 0xFF);
    } else {
        return (uint8_t)((SystemFontTable[index].bottomRows >> ((7 - r) * 8)) & 0xFF);
    }
}

